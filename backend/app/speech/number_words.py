def _en_under_100(n: int) -> str:
    if n in EN_ONES:
        return EN_ONES[n]
    tens = (n // 10) * 10
    rem = n % 10
    if rem == 0:
        return EN_TENS[tens]
    return f"{EN_TENS[tens]} {EN_ONES[rem]}"


def _format_in_words(num: int, lang: Lang) -> str:
    if num == 0:
        if lang == "hi":
            return HI_ONES[0]
        elif lang == "kn":
            return KN_ONES[0]
        else:
            return EN_ONES[0]

    crore = num // 10000000
    num %= 10000000
    lakh = num // 100000
    num %= 100000
    thousand = num // 1000
    num %= 1000
    hundred = num // 100
    rem = num % 100

    parts = []

    def get_under_100(val: int) -> str:
        if lang == "hi":
            return HI_ONES[val]
        elif lang == "kn":
            return KN_ONES[val]
        else:
            return _en_under_100(val)

    # Crore
    if crore > 0:
        parts.append(get_under_100(crore))
        parts.append("करोड़" if lang == "hi" else ("ಕೋಟಿ" if lang == "kn" else "crore"))

    # Lakh
    if lakh > 0:
        parts.append(get_under_100(lakh))
        parts.append("लाख" if lang == "hi" else ("ಲಕ್ಷ" if lang == "kn" else "lakh"))

    # Thousand
    if thousand > 0:
        parts.append(get_under_100(thousand))
        parts.append("हज़ार" if lang == "hi" else ("ಸಾವಿರ" if lang == "kn" else "thousand"))

    # Hundred
    if hundred > 0:
        parts.append(get_under_100(hundred))
        parts.append("सौ" if lang == "hi" else ("ನೂರು" if lang == "kn" else "hundred"))

    # Remainder 1-99
    if rem > 0:
        parts.append(get_under_100(rem))

    return " ".join(parts)


def rupees_in_words(paise: int, language: Lang) -> str:
    if paise < 0:
        raise ValueError("Negative paise not allowed")

    rupees = paise // 100
    rem_paise = paise % 100

    if language == "hi":
        r_unit = "रुपया" if rupees == 1 else "रुपये"
        r_text = f"{_format_in_words(rupees, 'hi')} {r_unit}"
        if rem_paise > 0:
            return f"{r_text} {HI_ONES[rem_paise]} पैसे"
        return r_text

    elif language == "kn":
        r_text = f"{_format_in_words(rupees, 'kn')} ರೂಪಾಯಿ"
        if rem_paise > 0:
            return f"{r_text} {KN_ONES[rem_paise]} ಪೈಸೆ"
        return r_text

    else:  # en
        r_unit = "rupee" if rupees == 1 else "rupees"
        r_text = f"{_format_in_words(rupees, 'en')} {r_unit}"
        if rem_paise > 0:
            return f"{r_text} and {_en_under_100(rem_paise)} paise"
        return r_text
